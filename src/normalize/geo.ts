const norm = (s: string) => s.trim().toLowerCase().replace(/\s+/g, ' ');

/** alias -> canonical country name */
export const COUNTRY_LOOKUP: ReadonlyMap<string, string> = new Map(
  COUNTRIES.flatMap(([canonical, iso, ...aliases]) => [
    [norm(canonical), canonical] as [string, string],
    [norm(iso), canonical] as [string, string],
    ...aliases.map((a) => [norm(a), canonical] as [string, string]),
  ]),
);

export interface CityRecord { city: string; admin: string; country: string; lat: number; lng: number }

/** normalised city name -> record. Ambiguous names resolve to the first (larger) entry. */
export const CITY_LOOKUP: ReadonlyMap<string, CityRecord> = new Map(
  CITIES.map(([city, admin, country, lat, lng]) => [norm(city), { city, admin, country, lat, lng }]),
);

export const STATE_LOOKUP: ReadonlyMap<string, string> = new Map(
  Object.entries(STATE_ABBR).map(([k, v]) => [k, v]),
);

export const ALL_STATE_NAMES: ReadonlySet<string> = new Set(
  Object.values(STATE_ABBR).map(norm),
);

